-- ==============================================================================
-- 1. Table: portfolio_contacts (Lead & Inquiry CRM)
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.portfolio_contacts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT,
  call_whatsapp_permission BOOLEAN DEFAULT FALSE,
  topic TEXT,
  urgency TEXT,
  message TEXT NOT NULL,
  status TEXT DEFAULT 'new',             -- 'new', 'reviewed', 'in_discussion', 'interview_scheduled', 'archived'
  admin_notes TEXT DEFAULT '',           -- Private notes from Tejas
  starred BOOLEAN DEFAULT FALSE,         -- Priority flag
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- Safely add CRM columns if the table already existed without them
DO $$ 
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='portfolio_contacts' AND column_name='status') THEN
    ALTER TABLE public.portfolio_contacts ADD COLUMN status TEXT DEFAULT 'new';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='portfolio_contacts' AND column_name='admin_notes') THEN
    ALTER TABLE public.portfolio_contacts ADD COLUMN admin_notes TEXT DEFAULT '';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='portfolio_contacts' AND column_name='starred') THEN
    ALTER TABLE public.portfolio_contacts ADD COLUMN starred BOOLEAN DEFAULT FALSE;
  END IF;
END $$;

-- Enable Row Level Security (RLS)
ALTER TABLE public.portfolio_contacts ENABLE ROW LEVEL SECURITY;

-- Drop existing policies first to prevent Error 42710 (policy already exists)
DROP POLICY IF EXISTS "Allow public anonymous inserts" ON public.portfolio_contacts;
DROP POLICY IF EXISTS "Allow authenticated users to view contacts" ON public.portfolio_contacts;
