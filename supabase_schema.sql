-- ==============================================================================
-- Tejas Portfolio - Supabase Database Schema
-- Table: portfolio_contacts
-- Description: Stores inquiries & direct contact submissions from the portfolio
-- ==============================================================================

-- 1. Create table for portfolio contacts
CREATE TABLE IF NOT EXISTS public.portfolio_contacts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT,
  call_whatsapp_permission BOOLEAN DEFAULT FALSE,
  topic TEXT,
  urgency TEXT,
  message TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 2. Enable Row Level Security (RLS) on the table
ALTER TABLE public.portfolio_contacts ENABLE ROW LEVEL SECURITY;

-- 3. Policy: Allow anyone (anon / website visitors) to INSERT their form responses
CREATE POLICY "Allow public anonymous inserts"
  ON public.portfolio_contacts
  FOR INSERT
  TO anon
  WITH CHECK (true);

-- 4. Policy: Allow only authenticated users (you in the Supabase Dashboard) to VIEW/READ responses
CREATE POLICY "Allow authenticated users to view contacts"
  ON public.portfolio_contacts
  FOR SELECT
  TO authenticated
  USING (true);

-- 5. Optional: Add an index on created_at for fast chronological queries
CREATE INDEX IF NOT EXISTS idx_portfolio_contacts_created_at
  ON public.portfolio_contacts (created_at DESC);


-- ==============================================================================
-- Table: portfolio_events
-- Description: Records project views, dashboard clicks, and telemetry events
-- ==============================================================================

-- 6. Create table for portfolio telemetry & project views
CREATE TABLE IF NOT EXISTS public.portfolio_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_name TEXT NOT NULL,
  project_id TEXT,
  project_name TEXT,
  metadata JSONB DEFAULT '{}'::jsonb,
  page_path TEXT DEFAULT '/',
  referrer TEXT,
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 7. Enable Row Level Security (RLS)
ALTER TABLE public.portfolio_events ENABLE ROW LEVEL SECURITY;

-- 8. Policy: Allow visitors / anonymous telemetry inserts
CREATE POLICY "Allow anonymous telemetry inserts"
  ON public.portfolio_events
  FOR INSERT
  TO anon
  WITH CHECK (true);

-- 9. Policy: Allow owner to view / query analytics
CREATE POLICY "Allow authenticated analytics queries"
  ON public.portfolio_events
  FOR SELECT
  TO authenticated
  USING (true);

-- 10. Performance Indexes for fast project-level aggregation
CREATE INDEX IF NOT EXISTS idx_portfolio_events_project_id
  ON public.portfolio_events (project_id, event_name);

CREATE INDEX IF NOT EXISTS idx_portfolio_events_created_at
  ON public.portfolio_events (created_at DESC);

