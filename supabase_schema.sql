-- ==============================================================================
-- 2. Table: portfolio_events (Telemetry, Heatmap & Traffic Analytics)
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.portfolio_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_name TEXT NOT NULL,              -- 'page_view', 'section_view', 'project_view', 'resume_download', etc.
  event_category TEXT DEFAULT 'general', -- 'traffic', 'section', 'project', 'resume', 'cta', 'conversion'
  visitor_id TEXT,                       -- Anonymous persistent client UUID
  session_id TEXT,                       -- Session identifier
  project_id TEXT,                       -- Project identifier (e.g. 'hotel-revenue')
  project_name TEXT,                     -- Human-readable project name
  section_id TEXT,                       -- Section identifier (e.g. 'projects', 'about')
  element TEXT,                          -- Specific element data-track tag (e.g. 'credly-pl300')
  dwell_time_seconds NUMERIC DEFAULT 0,  -- Time spent in seconds
  platform_source TEXT DEFAULT 'direct', -- 'linkedin', 'github', 'google', 'direct', 'twitter', etc.
  utm_source TEXT,                       -- UTM campaign source
  utm_medium TEXT,                       -- UTM campaign medium
  utm_campaign TEXT,                     -- UTM campaign name
  country TEXT,                          -- Visitor Country (e.g. 'India', 'United States')
  city TEXT,                             -- Visitor City (e.g. 'Pune', 'New York')
  device_type TEXT,                      -- 'desktop', 'mobile', 'tablet'
  browser TEXT,                          -- 'chrome', 'safari', 'edge', 'firefox'
  os TEXT,                               -- 'windows', 'macos', 'android', 'ios', 'linux'
  screen_resolution TEXT,                -- '1920x1080', '390x844'
  country_timezone TEXT,                 -- e.g. 'Asia/Kolkata', 'America/New_York'
  is_bot BOOLEAN DEFAULT FALSE,          -- Flagged automated traffic / crawler
  metadata JSONB DEFAULT '{}'::jsonb,    -- Extended metadata
  page_path TEXT DEFAULT '/',
  referrer TEXT,
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

