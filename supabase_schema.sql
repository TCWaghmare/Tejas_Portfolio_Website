-- ==============================================================================
-- Tejas Portfolio - Supabase Database Schema
-- Table: portfolio_contacts
-- Description: Stores inquiries & direct contact submissions from the portfolio
-- ==============================================================================

-- 1. Create table for portfolio contacts
CREATE TABLE IF NOT EXISTS public.portfolio_contacts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT,
  call_whatsapp_permission BOOLEAN DEFAULT FALSE,
  topic TEXT,
  urgency TEXT,
  message TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 2. Enable Row Level Security (RLS) on the table
ALTER TABLE public.portfolio_contacts ENABLE ROW LEVEL SECURITY;

-- 3. Policy: Allow anyone (anon / website visitors) to INSERT their form responses
CREATE POLICY "Allow public anonymous inserts"
  ON public.portfolio_contacts
  FOR INSERT
  TO anon
  WITH CHECK (true);

-- 4. Policy: Allow only authenticated users (you in the Supabase Dashboard) to VIEW/READ responses
CREATE POLICY "Allow authenticated users to view contacts"
  ON public.portfolio_contacts
  FOR SELECT
  TO authenticated
  USING (true);

-- 5. Optional: Add an index on created_at for fast chronological queries
CREATE INDEX IF NOT EXISTS idx_portfolio_contacts_created_at
  ON public.portfolio_contacts (created_at DESC);
